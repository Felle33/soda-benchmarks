#!/usr/bin/env python3
"""Stage compiler host object and opaque fixtures for the generic ESP harness.

This script cannot emit invocations, loops or a network schedule. Those are
already in host-riscv.o, produced from the C++ MLIR host-lowering pass.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('compiled',type=Path,help='pytorch_to_esp.py output directory')
    p.add_argument('output',type=Path)
    p.add_argument('--second-fixture',type=Path)
    a=p.parse_args();root=a.compiled.resolve();generated=root/'generated'
    fixture=json.loads((root/'fixture.json').read_text())
    plan=json.loads((generated/'network.json').read_text())
    if len(plan['input_elements'])!=1:
        raise ValueError('The generic CNN board harness takes exactly one input')
    out=a.output.resolve();out.mkdir(parents=True,exist_ok=False)
    files={'input':root/fixture['arguments'][0]['file'],
           'parameters':generated/'parameters.bin','reference':root/'reference.bin'}
    if a.second_fixture:
        other=json.loads((a.second_fixture/'fixture.json').read_text())
        assert [x['shape'] for x in other['arguments']]==[x['shape'] for x in fixture['arguments']]
        assert other['output_shape']==fixture['output_shape']
        assert (a.second_fixture/'generated/parameters.bin').read_bytes()==(generated/'parameters.bin').read_bytes(), 'Second input must use the same normalized parameters'
        files.update(input_second=a.second_fixture/other['arguments'][0]['file'],
                     reference_second=a.second_fixture/'reference.bin')
    sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
    assembly=['.section .rodata.nn,"a",@progbits']
    for name,src in files.items():
        count=plan['parameter_elements'] if name=='parameters' else (
            plan['output_elements'] if name.startswith('reference') else plan['input_elements'][0])
        assert src.stat().st_size==4*count, 'Fixture size disagrees with compiler manifest'
        shutil.copy2(src,out/(name+'.bin'))
        assembly+=['.balign 64','.global nn_'+name,'nn_'+name+':','.incbin "'+name+'.bin"']
    shutil.copy2(generated/'host-riscv.o',out/'host.o')
    shutil.copy2(generated/'network.json',out/'network.json')
    # Existing generic linker/allocator uses this name; only size metadata.
    (out/'plan.json').write_text(json.dumps({'arena_data_bytes':plan['arena_bytes']},indent=2)+'\n')
    (out/'tensors.S').write_text('\n'.join(assembly)+'\n')
    (out/'model.h').write_text(
        f'#define NN_OUTPUT_ELEMENTS {plan["output_elements"]}\n'
        f'#define NN_ARENA_BYTES {plan["arena_bytes"]+256}\n'
        f'#define NN_ATOL {fixture["atol"]!r}f\n#define NN_RTOL {fixture["rtol"]!r}f\n')
    (out/'stage.json').write_text(json.dumps(dict(scope='packaging only; host generated by MLIR',
        source=str(root),host_sha256=sha(out/'host.o'),
        fixture_sha256=sha(root/'fixture.json'),manifest_sha256=sha(generated/'network.json'),
        files={p.name:sha(p) for p in out.iterdir() if p.is_file()}),indent=2)+'\n')


if __name__=='__main__':main()
